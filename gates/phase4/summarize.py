def _load(report_paths: list[Path]) -> dict[str, Mapping[str, Any]]:
    problems: list[str] = []
    by_gate: dict[str, list[tuple[Path, Mapping[str, Any]]]] = {}
    for path in report_paths:
        try:
            report = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            problems.append(f"{path}: cannot read JSON ({exc})")
            continue
        if not isinstance(report, Mapping):
            problems.append(f"{path}: not a JSON object")
            continue
        invalid = validate_report(report)
        if invalid:
            problems += [f"{path}: {problem}" for problem in invalid]
            continue
        if report["gate_id"] not in PHASE4_GATE_IDS:
            problems.append(f"{path}: {report['gate_id']} is not a Phase 4 gate")
            continue
        by_gate.setdefault(report["gate_id"], []).append((Path(path), report))
    for gate_id in PHASE4_GATE_IDS:
        found = by_gate.get(gate_id, [])
        if not found:
            problems.append(f"no report for {gate_id}")
        elif len(found) > 1:
            problems.append(f"{len(found)} reports for {gate_id}: {', '.join(str(p) for p, _ in found)}")
    if problems:
        raise ValueError("cannot summarize:\n" + "\n".join(f"  - {p}" for p in problems))
    return {gate_id: by_gate[gate_id][0][1] for gate_id in PHASE4_GATE_IDS}


def _verdict(status: dict[str, str]) -> str:
    not_passed = [gate_id for gate_id in VERDICT_GATES if status[gate_id] != "pass"]
    if not not_passed:
        return ("The gates support H4: G4.1, G4.2, G4.3 and G4.5 all pass. G4.4 records, not judges; its numbers are"
                " below. Whether each badge now carries its model-level result, and your own session with both demos"
                " on the scrubber, are the rest of the evidence.")
    items = "\n".join(f"- {gate_id} {GATE_NAMES[gate_id]}: {STATUS_TEXT[status[gate_id]]}. The spec's next step:"
                       f" {ON_FAILURE[gate_id]}." for gate_id in not_passed)
    return f"The gates do **not** yet support H4. These gates did not pass:\n\n{items}"


def _behaviour(m: Mapping[str, Any]) -> list[str]:
    ind_chance, two_chance = m["induction_chance"], m["two_hop_chance"]
    ind_bar, two_bar = f"<= 2 x chance ({_pct(_twice(ind_chance))})", f"<= 2 x chance ({_pct(_twice(two_chance))})"
    rows = [
        ("Induction", "mechanism positions", m["induction_mechanism_accuracy"], ">= 90%",
         _at_least(m["induction_mechanism_accuracy"], 0.9)),
        ("Induction", "control positions", m["induction_control_accuracy"], ind_bar,
         _at_most(m["induction_control_accuracy"], _twice(ind_chance))),
        ("Induction", "random-weights twin", m["induction_twin_accuracy"], ind_bar,
         _at_most(m["induction_twin_accuracy"], _twice(ind_chance))),
        ("Two-hop", "held-out windows", m["two_hop_accuracy"], ">= 90%", _at_least(m["two_hop_accuracy"], 0.9)),
        ("Two-hop", "broken chains", m["two_hop_broken_accuracy"], two_bar,
         _at_most(m["two_hop_broken_accuracy"], _twice(two_chance))),
        ("Two-hop", "random-weights twin", m["two_hop_twin_accuracy"], two_bar,
         _at_most(m["two_hop_twin_accuracy"], _twice(two_chance))),
    ]
    lines = [
        "Accuracy from logits alone at each model's final checkpoint, beside its bar.",
        "",
        "| Model | Measured on | Accuracy | Bar | Met |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {model} | {where} | {_pct(value)} | {bar} | {met} |" for model, where, value, bar, met in rows]
    models = m.get("models") if isinstance(m.get("models"), Mapping) else {}
    recompute = []
    for name in MODEL_NAMES:
        r = models.get(name) if isinstance(models.get(name), Mapping) else {}
        recompute.append(f"{MODEL_NAMES[name]}: {_yes(r.get('recompute_identical'))}")
    lines += [
        "",
        f"The seeded recompute matched the first run's final state: {_yes(m['recompute_identical'])}"
        f" ({'; '.join(recompute)}). {_num(m['checkpoints_written'], ',')} of {_num(m['checkpoints_scheduled'], ',')}"
        f" checkpoints written and {_num(m['events_recorded'], ',')} of {_num(m['events_expected'], ',')} trace events"
        " recorded.",
    ]
    errors = [f"{MODEL_NAMES[name]}: {_cell(models[name]['error'])}" for name in MODEL_NAMES
              if isinstance(models.get(name), Mapping) and models[name].get("error")]
    if errors:
        lines += ["", "The trace stopped early. " + " ".join(errors)]
    return lines


def _induction(m: Mapping[str, Any]) -> list[str]:
    after0, after1 = m["patch_after_block0_min"], m["patch_after_block1_max"]
    uniform = m["uniform_baseline"]
    rows = [
        ("Attention view", "best block-1 head's attention to induction targets", _pct(m["best_head_attention"]),
         ">= 50%", _at_least(m["best_head_attention"], 0.5)),
        ("Attention view", "the twin's best head", _pct(m["twin_best_attention"]),
         f"<= 2 x uniform ({_pct(_twice(uniform))})", _at_most(m["twin_best_attention"], _twice(uniform))),
        ("Ablation", f"block-1 heads {_heads(m['induction_heads'])} zeroed together",
         _fraction(m["ablation_fraction_removed"]), "removes >= 0.5", _at_least(m["ablation_fraction_removed"], 0.5)),
        ("Component swap", f"block 1's attention from step {_num(m['swap_step'], ',')}",
         _fraction(m["swap_fraction_removed"]), "removes >= 0.5", _at_least(m["swap_fraction_removed"], 0.5)),
        ("Patch", "followed after block 0, lowest target", _pct(after0), ">= 90%", _at_least(after0, 0.9)),
        ("Patch", "followed after block 1, highest target", _pct(after1), "<= 10%", _at_most(after1, 0.1)),
    ]
    lines = [
        f"At the induction model's final checkpoint: mechanism accuracy {_pct(m['mechanism_accuracy'])}, chance"
        f" {_pct(m['chance'])}. A fraction removed is the share of the accuracy above chance an edit takes away; it"
        " can exceed 1 when accuracy falls below chance.",
        "",
        "| Test | Measured | Result | Bar | Met |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {test} | {what} | {value} | {bar} | {met} |" for test, what, value, bar, met in rows]
    attention = m["attention_by_head"] if isinstance(m["attention_by_head"], list) else []
    by_head = m["fraction_removed_by_head"] if isinstance(m["fraction_removed_by_head"], Mapping) else {}
    lines += [
        "",
        "Each head on its own, recorded, not compared: models grow redundant induction heads, so zeroing one may remove"
        " nothing.",
        "",
        "| Head | Attention to induction targets | Fraction removed when zeroed alone |",
        "| --- | --- | --- |",
    ]
    for key in _numbered(by_head):
        removed = by_head[key]
        layer, _, head = str(key).partition(".")
        shown = _pct(attention[int(head)]) if layer == "1" and head.isdigit() and int(head) < len(attention) else "n/a"
        lines.append(f"| block {_cell(layer)}, head {_cell(head)} | {shown} | {_fraction(removed)} |")
    if not by_head:
        lines.append("| no heads recorded | | |")
    followed = m["patch_followed_by_tap"] if isinstance(m["patch_followed_by_tap"], Mapping) else {}
    targets = m.get("patch_targets") if isinstance(m.get("patch_targets"), list) else []
    lines += [
        "",
        "The patch, by tap and copy target: how often the prediction follows the new token.",
        "",
        "| Patched at | " + " | ".join(f"target {_cell(j)}" for j in targets) + " |",
        "| --- |" + " --- |" * len(targets),
    ]
    for tap in _ordered(followed, PATCH_TAPS):
        rates = followed[tap] if isinstance(followed[tap], list) else []
        lines.append(f"| {_cell(tap)} | " + " | ".join(_pct(rate) for rate in rates) + " |")
    return lines


def _profile_rows(profile: Any, label: str) -> list[str]:
    profile = profile if isinstance(profile, Mapping) else {}
    rows = []
    for site in _ordered(profile, SITES):
        rates = profile[site] if isinstance(profile[site], list) else []
        rows.append(f"| {label} | {_cell(site)} | " + " | ".join(_pct(rate) for rate in rates) + " |")
    return rows


def _blocks(m: Mapping[str, Any]) -> int:
    lengths = [len(rates) for profile in (m.get("swap_by_site"), m.get("control_unchanged_by_site"))
               if isinstance(profile, Mapping) for rates in profile.values() if isinstance(rates, list)]
    return max(lengths, default=0)


def _two_hop(m: Mapping[str, Any]) -> list[str]:
    best = m["best_swap"] if isinstance(m["best_swap"], Mapping) else {}
    blocks = _blocks(m)
    header = "| Rate | Site | " + " | ".join(f"after block {b}" for b in range(blocks)) + " |"
    lines = [
        f"Unpatched, the two-hop model answers `c` in {_pct(m['unpatched_accuracy'])} of the windows. Each block's"
        " output is patched at the site's positions from an aligned source, the target with its chain moved to the"
        " counterpart and a new answer, or from a control, the target with only the counterpart's object replaced.",
        "",
        f"Judged: the control leaves the answer unchanged at least {_pct(m['control_unchanged_min'])} of the time"
        f" at every site and block; the bar is 95% ({_at_least(m['control_unchanged_min'], 0.95)} met).",
        "",
        "Recorded, not judged (D36): the swap rate (the answer becomes the counterpart's successor `d`, so the"
        " intermediate moved) and the transplant rate (it becomes the source's `d′`, so the answer moved). The largest"
        f" swap is {_pct(best.get('rate'))}, at {_cell(best.get('site', 'no site'))} after block"
        f" {_num(best.get('block'), ',')}.",
        "",
        header,
        "| --- | --- |" + " --- |" * blocks,
        *_profile_rows(m["swap_by_site"], "Swap"),
        *_profile_rows(m["transplant_by_site"], "Transplant"),
        *_profile_rows(m["control_unchanged_by_site"], "Control unchanged"),
    ]
    return lines


def _lenses(m: Mapping[str, Any], g43: Mapping[str, Any]) -> list[str]:
    ranks = m["lens_ranks"] if isinstance(m["lens_ranks"], Mapping) else {}
    lines = [
        "Each lens's median rank of the intermediate `b` and the answer `c` at the query's positions, 0 being the top"
        " token, for the trained two-hop model and its random-weights twin, beside G4.3's swap at the query. Recorded,"
        " not judged (D34).",
        "",
        "| Model | Lens | Position | Block | Intermediate rank | Answer rank | G4.3 swap at the query |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    query_swap = (g43.get("swap_by_site") or {}).get("query") if isinstance(g43.get("swap_by_site"), Mapping) else None
    query_swap = query_swap if isinstance(query_swap, list) else []
    for model in ("trained", "twin"):
        by_lens = ranks.get(model) if isinstance(ranks.get(model), Mapping) else {}
        for lens in ("logit_lens", "jlens"):
            by_position = by_lens.get(lens) if isinstance(by_lens.get(lens), Mapping) else {}
            for position in _numbered(by_position):
                by_block = by_position[position] if isinstance(by_position[position], Mapping) else {}
                for block in _numbered(by_block):
                    pair = by_block[block] if isinstance(by_block[block], Mapping) else {}
                    swap = (_pct(query_swap[int(block)]) if model == "trained" and str(block).isdigit()
                            and int(block) < len(query_swap) else "")
                    lines.append(f"| {model} | {LENS_NAMES.get(lens, _cell(lens))} | {_cell(position)}"
                                 f" | {_cell(block)} | {_num(pair.get('intermediate'), 'g')}"
                                 f" | {_num(pair.get('answer'), 'g')} | {swap} |")
    swaps = m["jswap_by_layer"] if isinstance(m["jswap_by_layer"], Mapping) else {}
    lines += [
        "",
        "The J-lens coordinate swap: the intermediate's J-lens coordinates exchanged with the counterpart's at the"
        " query's positions, at each block's output (the last block's J is the identity, so there it is the logit"
        " lens's swap), beside G4.3's aligned patch at the query.",
        "",
        "| Block | Answer becomes `d` | Answer stays `c` | G4.3 swap at the query |",
        "| --- | --- | --- | --- |",
    ]
    for block in _numbered(swaps):
        pair = swaps[block] if isinstance(swaps[block], Mapping) else {}
        swap = _pct(query_swap[int(block)]) if str(block).isdigit() and int(block) < len(query_swap) else "n/a"
        lines.append(f"| {_cell(block)} | {_pct(pair.get('swap'))} | {_pct(pair.get('unchanged'))} | {swap} |")
    attribution = m["attribution"] if isinstance(m["attribution"], Mapping) else {}
    lines += [
        "",
        "Direct logit attribution: each part's mean contribution to the correct next token's logit at the mechanism"
        " positions, averaged over windows. Recorded, because an MLP may legitimately amplify what attention copies.",
        "",
        "| Model | Weights | Part | Mean contribution |",
        "| --- | --- | --- | --- |",
    ]
    for name, by_weights in attribution.items():
        by_weights = by_weights if isinstance(by_weights, Mapping) else {}
        for weights, parts in by_weights.items():
            parts = parts if isinstance(parts, Mapping) else {}
            for part in sorted(parts, key=_part_order):
                lines.append(f"| {MODEL_NAMES.get(name, _cell(name))} | {_cell(weights)} | {_cell(part)}"
                             f" | {_num(parts[part], '+.4f')} |")
    return lines


def _formation(m: Mapping[str, Any]) -> list[str]:
    loss, attention = m["formation_loss_step"], m["formation_attention_step"]
    same = (" They fall at the same checkpoint." if _is_number(loss) and loss == attention
            else " They fall at different checkpoints.")
    return [
        "On the induction model's trace, the step ending the steepest drop in the mechanism positions' loss, and the"
        " step ending the steepest rise in the best block-1 head's attention to its targets. Recorded.",
        "",
        "| Steepest loss drop | Steepest attention rise |",
        "| --- | --- |",
        f"| step {_num(loss, ',')} | step {_num(attention, ',')} |",
        "",
        f"Both zoo models' views built twice byte-identical: {_yes(m['builds_identical'])}; external URLs in the"
        f" viewer's files: {_num(m['external_urls'], ',')}." + (same if _is_number(loss) else ""),
    ]


def _key(gate_id: str, m: Mapping[str, Any]) -> str:
    if gate_id == "G4.1":
        return (f"induction {_pct(m['induction_mechanism_accuracy'])} at mechanism positions, two-hop"
                f" {_pct(m['two_hop_accuracy'])}; recompute identical: {_yes(m['recompute_identical'])};"
                f" {_num(m['events_recorded'], ',')} of {_num(m['events_expected'], ',')} events")
    if gate_id == "G4.2":
        return (f"best head {_pct(m['best_head_attention'])}; heads zeroed remove"
                f" {_fraction(m['ablation_fraction_removed'])}; swap from step {_num(m['swap_step'], ',')} removes"
                f" {_fraction(m['swap_fraction_removed'])}; patch {_pct(m['patch_after_block0_min'])} after block 0,"
                f" {_pct(m['patch_after_block1_max'])} after block 1")
    if gate_id == "G4.3":
        best = m["best_swap"] if isinstance(m["best_swap"], Mapping) else {}
        return (f"control unchanged at least {_pct(m['control_unchanged_min'])} (pass at 95%); largest swap"
                f" {_pct(best.get('rate'))}, recorded")
    if gate_id == "G4.4":
        swaps = m["jswap_by_layer"] if isinstance(m["jswap_by_layer"], Mapping) else {}
        return f"recorded, not judged; lens ranks, the coordinate swap at {len(swaps)} block outputs, attribution"
    return (f"formation steps {_num(m['formation_loss_step'], ',')} (loss) and"
            f" {_num(m['formation_attention_step'], ',')} (attention); builds identical: {_yes(m['builds_identical'])};"
            f" {_num(m['external_urls'], ',')} external URLs")


def _consistency(reports: Mapping[str, Mapping[str, Any]]) -> list[str]:
    lines = []
    commits = sorted({r["git_commit"] for r in reports.values()})
    locks = sorted({r["env_lock_sha256"] for r in reports.values()})
    lines.append(f"All five reports come from commit `{commits[0]}`." if len(commits) == 1
                 else f"The reports come from {len(commits)} different commits.")
    lines.append(f"All five reports come from lockfile `{locks[0]}`." if len(locks) == 1
                 else f"The reports come from {len(locks)} different lockfiles.")
    dirty = [gate_id for gate_id in PHASE4_GATE_IDS if reports[gate_id]["git_dirty"]]
    if dirty:
        lines.append(f"Written from a tree with uncommitted changes: {', '.join(dirty)}. Those reports can't be"
                     " reproduced from their commit alone.")
    return [" ".join(lines)]


def _ordered(mapping: Mapping[str, Any], order: tuple[str, ...]) -> list[str]:
    """``mapping``'s keys in ``order``, then any others, sorted."""
    return [key for key in order if key in mapping] + sorted(key for key in mapping if key not in order)


def _numbered(mapping: Mapping[str, Any]) -> list[str]:
    """Keys such as ``"3"`` or ``"1.2"`` in numeric order, then any others, sorted."""
    def number(key: str) -> tuple[int, ...] | None:
        parts = str(key).split(".")
        return tuple(int(part) for part in parts) if all(part.isdigit() for part in parts) else None

    numeric = sorted((key for key in mapping if number(key) is not None), key=number)
    return numeric + sorted(key for key in mapping if number(key) is None)


def _part_order(part: str) -> tuple[int, int, int, str]:
    """Forward order: the embeddings, each block's attention then MLP, the layer norm's bias, then the rest."""
    fixed = {"hook_embed": 0, "hook_pos_embed": 1}
    if part in fixed:
        return (0, fixed[part], 0, part)
    pieces = part.split(".")
    if len(pieces) == 3 and pieces[0] == "blocks" and pieces[1].isdigit():
        return (1, int(pieces[1]), {"hook_attn_out": 0, "hook_mlp_out": 1}.get(pieces[2], 2), part)
    return (2 if part == "ln_bias" else 3, 0, 0, part)


def _twice(value: Any) -> Any:
    return 2 * value if _is_number(value) else None


def _at_least(value: Any, bound: Any) -> str:
    return "not measured" if not (_is_number(value) and _is_number(bound)) else _yes(value >= bound)


def _at_most(value: Any, bound: Any) -> str:
    return "not measured" if not (_is_number(value) and _is_number(bound)) else _yes(value <= bound)


def _heads(heads: Any) -> str:
    if not isinstance(heads, list) or not heads:
        return "(none met the attention bar)"
    return ", ".join(_cell(head) for head in heads)


def _fraction(value: Any) -> str:
    return "not measured" if not _is_number(value) else f"{value:.3f}"


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _num(value: Any, style: str) -> str:
    if value is None:
        return "not measured"
    if isinstance(value, bool):
        return _yes(value)
    if not _is_number(value):
        return _cell(value)
    if style == ",":
        return f"{value:,.0f}" if isinstance(value, float) else f"{value:,}"
    return format(value, style)


def _pct(value: Any, digits: int = 1) -> str:
    return "not measured" if not _is_number(value) else f"{100 * value:.{digits}f}%"


def _yes(value: Any) -> str:
    return "not measured" if value is None else ("yes" if value else "no")


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


