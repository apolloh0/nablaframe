"""The Phase 4 summary: reports/phase4/summary.md, generated from the five Phase 4 reports.

Same rules as gates/phase3/summarize.py: never written by hand, a missing or invalid report
says so rather than being skipped, and every number comes from a report. Its H4 evidence:

* each zoo model's behaviour beside its bars, and whether the recompute matched
* G4.2's four tests beside their bars, with each head's ablation
* G4.3's control, and its swap and transplant profiles by site and block
* G4.4's lens ranks and coordinate-swap rates beside G4.3's swap profile, and the attribution
* the formation demo's two steps side by side
"""

# summarize() raises ValueError, naming every problem, when a report is unreadable, invalid
# (validate_report, which includes the status rules), not a Phase 4 report, or when the inputs
# are not exactly one report per gate. main() prints the problems, writes nothing and returns 1.
#
# A pure function of the report files: no timestamps of its own, rows in gate order. The
# verdict reads statuses only. G4.4 always passes, so the verdict covers G4.1, G4.2, G4.3 and
# G4.5, and G4.4's numbers are listed without a verdict of their own. Reports written from a
# dirty tree, or from different commits or lockfiles, are named as such. It never states a
# result that is not in a report. apolloh0 rules H4.
#
# Reports are canonical JSON, whose keys come back sorted, so the summary puts them back in the
# spec's order: G4.3's sites as ``SITES`` lists them, G4.2's patch taps from the input to block 1's
# output, attribution parts in forward order (embeddings, then each block's attention and MLP,
# then the layer norm's bias), and blocks and positions by number. Anything else follows, sorted.
# A rate is shown as a percentage; a median rank as a number, 0 being the top token.
#
# Run in nf-jax: ``UV_PROJECT_ENVIRONMENT=.venv-jax uv run --extra jax python
# gates/phase4/summarize.py``.

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from nablaframe.reports import PHASE4_GATE_IDS, validate_report

REPO_ROOT = Path(__file__).resolve().parents[2]
REPORTS_DIR = REPO_ROOT / "reports" / "phase4"
SUMMARY_PATH = REPORTS_DIR / "summary.md"

GATE_NAMES = {
    "G4.1": "Zoo training",
    "G4.2": "Induction",
    "G4.3": "Two-hop",
    "G4.4": "Lenses at model level",
    "G4.5": "Formation and viewer",
}
# The spec's "On failure" column, docs/specs/phase-4.md, Gates.
ON_FAILURE = {
    "G4.1": "diagnose the task or the model size; a size change is a ruling",
    "G4.2": "diagnose the view or tool that failed",
    "G4.3": "diagnose the patch",
    "G4.4": "not applicable",
    "G4.5": "diagnose the build",
}
RECORDED_GATES = ("G4.4",)
VERDICT_GATES = tuple(gate_id for gate_id in PHASE4_GATE_IDS if gate_id not in RECORDED_GATES)
STATUS_TEXT = {"pass": "pass", "conditional_pass": "conditional pass", "fail": "fail"}
LENS_NAMES = {"logit_lens": "Logit lens", "jlens": "J-lens"}
MODEL_NAMES = {"induction": "Induction", "two_hop": "Two-hop"}
# G4.3's sites, as gates/phase4/_common.py's TWO_HOP_SITES orders them, and G4.2's patch taps.
SITES = ("query", "fact positions", "every position")
PATCH_TAPS = ("blocks.0.hook_resid_pre", "blocks.0.hook_resid_post", "blocks.1.hook_resid_post")


def summarize(report_paths: list[Path]) -> str:
    reports = _load(report_paths)
    m = {gate_id: report["measurements"] for gate_id, report in reports.items()}
    status = {gate_id: report["status"] for gate_id, report in reports.items()}

    lines = [
        "# Phase 4 summary",
        "",
        "Generated by `gates/phase4/summarize.py` from the five Phase 4 gate reports. Do not edit by hand;"
        " regenerate with `UV_PROJECT_ENVIRONMENT=.venv-jax uv run --extra jax python gates/phase4/summarize.py`.",
        "",
        "## Gates",
        "",
        "| Gate | Status | Key measurements |",
        "| --- | --- | --- |",
    ]
    for gate_id in PHASE4_GATE_IDS:
        shown = "always passes" if gate_id in RECORDED_GATES else STATUS_TEXT[status[gate_id]]
        lines.append(f"| {gate_id} {GATE_NAMES[gate_id]} | {shown} | {_cell(_key(gate_id, m[gate_id]))} |")

    lines += [
        "",
        "## Provenance",
        "",
        "| Gate | Commit | Dirty tree | Env | Chip | Threads | XLA_FLAGS | Lockfile SHA-256 | Report time (UTC) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for gate_id in PHASE4_GATE_IDS:
        r = reports[gate_id]
        flags = f"`{_cell(r['xla_flags'])}`" if r["xla_flags"] else "none"
        lines.append(
            f"| {gate_id} | `{r['git_commit'][:12]}` | {_yes(r['git_dirty'])} | {r['env_name']} | {_cell(r['chip'])}"
            f" | {r['thread_count']} | {flags} | `{r['env_lock_sha256'][:12]}` | {r['timestamp_utc']} |"
        )
    lines += ["", *_consistency(reports)]

    lines += [
        "",
        "## H4 evidence",
        "",
        "H4 asks whether every shipped view and tool now carries a model-level result on its badge, and whether both"
        " signature demos reproduce.",
        "",
        _verdict(status),
        "",
        "### The zoo's behaviour (G4.1)",
        "",
        *_behaviour(m["G4.1"]),
        "",
        "### Induction: the attention view, ablation, component swap and patch (G4.2)",
        "",
        *_induction(m["G4.2"]),
        "",
        "### Two-hop: the aligned patch, the signature demo (G4.3)",
        "",
        *_two_hop(m["G4.3"]),
        "",
        "### Lenses, the coordinate swap and attribution at model level (G4.4)",
        "",
        *_lenses(m["G4.4"], m["G4.3"]),
        "",
        "### The induction formation demo (G4.5)",
        "",
        *_formation(m["G4.5"]),
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    parser.add_argument("--out", type=Path, default=SUMMARY_PATH)
    args = parser.parse_args(argv)
    paths = sorted(args.reports_dir.glob("g4*.json"))
    try:
        text = summarize(paths)
    except ValueError as exc:
        print(f"No summary written.\n{exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Summary written to {args.out}")
    return 0


