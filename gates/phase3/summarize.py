def _load(report_paths: list[Path]) -> dict[str, Mapping[str, Any]]:
    problems: list[str] = []
    by_gate: dict[str, list[tuple[Path, Mapping[str, Any]]]] = {}
    for path in report_paths:
        try:
            report = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            problems.append(f"{path}: cannot read JSON ({exc})")
            continue
        if not isinstance(report, Mapping):
            problems.append(f"{path}: not a JSON object")
            continue
        invalid = validate_report(report)
        if invalid:
            problems += [f"{path}: {problem}" for problem in invalid]
            continue
        if report["gate_id"] not in PHASE3_GATE_IDS:
            problems.append(f"{path}: {report['gate_id']} is not a Phase 3 gate")
            continue
        by_gate.setdefault(report["gate_id"], []).append((Path(path), report))
    for gate_id in PHASE3_GATE_IDS:
        found = by_gate.get(gate_id, [])
        if not found:
            problems.append(f"no report for {gate_id}")
        elif len(found) > 1:
            problems.append(f"{len(found)} reports for {gate_id}: {', '.join(str(p) for p, _ in found)}")
    if problems:
        raise ValueError("cannot summarize:\n" + "\n".join(f"  - {p}" for p in problems))
    return {gate_id: by_gate[gate_id][0][1] for gate_id in PHASE3_GATE_IDS}


def _verdict(status: dict[str, str]) -> str:
    not_passed = [gate_id for gate_id in VERDICT_GATES if status[gate_id] != "pass"]
    if not not_passed:
        return ("The gates support H3: G3.1, G3.2 and G3.5 all pass. G3.3 and G3.4 record, not judge; their numbers"
                " are below. Your own session with the compare mode is the rest of the evidence.")
    items = "\n".join(f"- {gate_id} {GATE_NAMES[gate_id]}: {STATUS_TEXT[status[gate_id]]}. The spec's next step:"
                       f" {ON_FAILURE[gate_id]}." for gate_id in not_passed)
    return f"The gates do **not** yet support H3. These gates did not pass:\n\n{items}"


def _identities(m: Mapping[str, Any]) -> list[str]:
    exact = m["identities_by_kind"] if isinstance(m["identities_by_kind"], Mapping) else {}
    checked = m.get("identities_checked_by_kind")
    checked = checked if isinstance(checked, Mapping) else {}
    kinds = [kind for kind in IDENTITY_KINDS if kind in exact] + sorted(set(exact) - set(IDENTITY_KINDS))
    lines = [
        f"{_num(m['identities_exact'], ',')} of {_num(m['identities_checked'], ',')} identities reproduced bit for bit"
        f" at step {_num(m.get('step'), ',')}, on the probe. D25's identities, by kind:",
        "",
        "| Identity | Exact | Checked |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {_cell(kind)} | {_num(exact[kind], ',')} | {_num(checked.get(kind), ',')} |" for kind in kinds]
    return lines


def _experiment(m: Mapping[str, Any]) -> list[str]:
    results = m["results_by_layer"] if isinstance(m["results_by_layer"], Mapping) else {}
    layers = m["layers"] if isinstance(m["layers"], list) else []
    factors = m["scale_factors"] if isinstance(m["scale_factors"], list) else []
    positions = m.get("positions")
    count = f"{len(positions):,} seeded positions" if isinstance(positions, list) else "seeded positions"
    lines = [
        f"Steering each block's output at {count} in the fit range, each toward a seeded token, along the J-lens"
        " direction and the logit-lens direction, at the final step, on the probe. Each cell is the mean change in"
        " the token's logit at the steered position, then its mean change over the next"
        f" {_num(m.get('later_window', 16), ',')} positions, then their ratio (later over same). Recorded, not"
        " judged: if the J-lens reads what a residual tells later positions, its direction moves later positions"
        " more and the same position less than the logit lens's does.",
        "",
        "| Block output | Scale | J-lens: same | J-lens: later | J-lens: ratio | Logit lens: same | Logit lens: later"
        " | Logit lens: ratio |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for layer in layers:
        by_scale = results.get(str(layer))
        by_scale = by_scale if isinstance(by_scale, Mapping) else {}
        for factor in factors:
            row = by_scale.get(_factor(factor))
            row = row if isinstance(row, Mapping) else {}
            cells = []
            for direction in ("jlens", "logit_lens"):
                values = row.get(direction) if isinstance(row.get(direction), Mapping) else {}
                cells += [_num(values.get("same_position"), "+.4f"), _num(values.get("later_positions"), "+.4f"),
                          _num(values.get("ratio"), ".4f")]
            lines.append(f"| block {_cell(layer)} | {_cell(factor)}x | " + " | ".join(cells) + " |")
    if not layers or not factors:
        lines.append("| no layers or scales recorded | | | | | | | |")
    return lines


def _fit_range(m: Mapping[str, Any]) -> list[str]:
    by_step = m["meters_by_step"] if isinstance(m["meters_by_step"], Mapping) else {}
    steps = [step for step in by_step if str(step).isdigit()]
    if not steps:
        return ["The fit-range meters have no step to show."]
    final = max(steps, key=int)
    meters = by_step[final] if isinstance(by_step[final], Mapping) else {}
    span = m.get("fit_range")
    span_text = (f"positions {_num(span[0], ',')} to {_num(span[1], ',')}" if isinstance(span, list) and len(span) == 2
                 else "D17's fit range")
    lines = [
        f"Both lenses' meters at the final step, {int(final):,}, on the probe: on every position, and on {span_text}"
        " only, the positions J's fit uses. Recorded, not judged.",
        "",
        "| Lens | Reading | KL, full probe (nats) | KL, fit range (nats) | Top-1 agreement, full probe"
        " | Top-1 agreement, fit range |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for lens in ("logit_lens", "jlens"):
        pair = meters.get(lens) if isinstance(meters.get(lens), Mapping) else {}
        full = pair.get("full") if isinstance(pair.get("full"), list) else []
        fit = pair.get("fit_range") if isinstance(pair.get("fit_range"), list) else []
        for i in range(max(len(full), len(fit))):
            a = full[i] if i < len(full) and isinstance(full[i], Mapping) else {}
            b = fit[i] if i < len(fit) and isinstance(fit[i], Mapping) else {}
            lines.append(f"| {LENS_NAMES[lens]} | {_reading(lens, a.get('layer', b.get('layer', i)))}"
                         f" | {_num(a.get('kl_mean'), 'e')} | {_num(b.get('kl_mean'), 'e')}"
                         f" | {_pct(a.get('top1_agreement'))} | {_pct(b.get('top1_agreement'))} |")
    return lines


def _reading(lens: str, layer: Any) -> str:
    if not _is_number(layer):
        return _cell(layer)
    if lens == "logit_lens":
        return "stream entering block 0" if layer == 0 else f"block {int(layer) - 1}'s output"
    return f"block {int(layer)}'s output"


def _key(gate_id: str, m: Mapping[str, Any]) -> str:
    if gate_id == "G3.1":
        return (f"{_num(m['identities_exact'], ',')} of {_num(m['identities_checked'], ',')} identities bit for bit"
                " (pass when all are)")
    if gate_id == "G3.2":
        return (f"{_num(m['recompute_identical'], ',')} of {_num(m['sample_size'], ',')} sampled interventions"
                f" byte-identical over three runs, the last after deleting the cache; cache keys distinct and stable:"
                f" {_yes(m['cache_keys_distinct'])}")
    if gate_id == "G3.3":
        layers = m["layers"] if isinstance(m["layers"], list) else []
        return f"recorded, not judged; {len(layers)} block outputs at {_num(len(m['scale_factors'] or []), ',')} scales"
    if gate_id == "G3.4":
        steps = m["meters_by_step"] if isinstance(m["meters_by_step"], Mapping) else {}
        return f"recorded, not judged; both lenses' meters at {len(steps):,} trace steps"
    return (f"builds identical: {_yes(m['builds_identical'])}; {_num(m['external_urls'], ',')} external URLs in the"
            f" viewer's files; {_num(m['payloads'], ',')} payloads")


def _consistency(reports: Mapping[str, Mapping[str, Any]]) -> list[str]:
    lines = []
    commits = sorted({r["git_commit"] for r in reports.values()})
    locks = sorted({r["env_lock_sha256"] for r in reports.values()})
    lines.append(f"All five reports come from commit `{commits[0]}`." if len(commits) == 1
                 else f"The reports come from {len(commits)} different commits.")
    lines.append(f"All five reports come from lockfile `{locks[0]}`." if len(locks) == 1
                 else f"The reports come from {len(locks)} different lockfiles.")
    dirty = [gate_id for gate_id in PHASE3_GATE_IDS if reports[gate_id]["git_dirty"]]
    if dirty:
        lines.append(f"Written from a tree with uncommitted changes: {', '.join(dirty)}. Those reports can't be"
                     " reproduced from their commit alone.")
    return [" ".join(lines)]


def _factor(factor: Any) -> str:
    """A scale factor as G3.3's report keys it: ``"0.25"``, ``"0.5"``, ``"1.0"``."""
    return repr(float(factor)) if _is_number(factor) else str(factor)


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _num(value: Any, style: str) -> str:
    if value is None:
        return "not measured"
    if isinstance(value, bool):
        return _yes(value)
    if not _is_number(value):
        return _cell(value)
    if style == ",":
        return f"{value:,.0f}" if isinstance(value, float) else f"{value:,}"
    if style == "e":
        return "0" if value == 0 else f"{value:.3e}"
    return format(value, style)


def _pct(value: Any, digits: int = 1) -> str:
    return "not measured" if not _is_number(value) else f"{100 * value:.{digits}f}%"


def _yes(value: Any) -> str:
    return "not measured" if value is None else ("yes" if value else "no")


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


