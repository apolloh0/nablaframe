"""The Phase 3 summary: reports/phase3/summary.md, from the five Phase 3 reports.

Same rules as gates/phase2/summarize.py. Its H3 evidence gives G3.1's identities by kind, and
G3.3's and G3.4's recorded numbers: the J-lens experiment per layer and scale, and the
fit-range meters at the final step beside the full-probe ones.
"""

# summarize() raises ValueError, naming every problem, when a report is unreadable,
# invalid (validate_report, which includes the status rules), not a Phase 3 report, or
# when the inputs are not exactly one report per gate. main() prints the problems,
# writes nothing and returns 1.
#
# A pure function of the report files: no timestamps of its own, rows in gate order.
# The verdict reads statuses only. G3.3 and G3.4 always pass, so the verdict covers G3.1,
# G3.2 and G3.5, and G3.3's and G3.4's numbers are listed without a verdict of their own.
# Reports written from a dirty tree, or from different commits or lockfiles, are named
# as such. It never states a result that is not in a report. apolloh0 rules H3.
#
# G3.3's layers and scales are listed in the order its ``layers`` and ``scale_factors``
# give them, each scale looked up in ``results_by_layer`` under its report key ("0.25",
# "0.5", "1.0"). G3.4's final step is the largest key of ``meters_by_step`` read as a step
# number. A logit-lens reading is named by the stream it reads: reading 0 is the stream
# entering block 0, reading l + 1 block l's output; a J-lens reading l is block l's output.
#
# Run in nf-jax: ``UV_PROJECT_ENVIRONMENT=.venv-jax uv run --extra jax python
# gates/phase3/summarize.py``.

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from nablaframe.reports import PHASE3_GATE_IDS, validate_report

REPO_ROOT = Path(__file__).resolve().parents[2]
REPORTS_DIR = REPO_ROOT / "reports" / "phase3"
SUMMARY_PATH = REPORTS_DIR / "summary.md"

GATE_NAMES = {
    "G3.1": "Exactness identities",
    "G3.2": "Determinism and caching",
    "G3.3": "The J-lens experiment",
    "G3.4": "The fit-range meters",
    "G3.5": "Viewer compare mode",
}
# The spec's "On failure" column, docs/specs/phase-3.md, Gates.
ON_FAILURE = {
    "G3.1": "diagnose the tool before any effect is trusted",
    "G3.2": "diagnose the cache",
    "G3.3": "not applicable",
    "G3.4": "not applicable",
    "G3.5": "diagnose the export",
}
RECORDED_GATES = ("G3.3", "G3.4")
VERDICT_GATES = tuple(gate_id for gate_id in PHASE3_GATE_IDS if gate_id not in RECORDED_GATES)
IDENTITY_KINDS = ("null edit", "steering at zero", "self-swap", "full patch", "full swap")
STATUS_TEXT = {"pass": "pass", "conditional_pass": "conditional pass", "fail": "fail"}
LENS_NAMES = {"logit_lens": "Logit lens", "jlens": "J-lens"}


def summarize(report_paths: list[Path]) -> str:
    reports = _load(report_paths)
    m = {gate_id: report["measurements"] for gate_id, report in reports.items()}
    status = {gate_id: report["status"] for gate_id, report in reports.items()}

    lines = [
        "# Phase 3 summary",
        "",
        "Generated by `gates/phase3/summarize.py` from the five Phase 3 gate reports. Do not edit by hand;"
        " regenerate with `UV_PROJECT_ENVIRONMENT=.venv-jax uv run --extra jax python gates/phase3/summarize.py`.",
        "",
        "## Gates",
        "",
        "| Gate | Status | Key measurements |",
        "| --- | --- | --- |",
    ]
    for gate_id in PHASE3_GATE_IDS:
        shown = "always passes" if gate_id in RECORDED_GATES else STATUS_TEXT[status[gate_id]]
        lines.append(f"| {gate_id} {GATE_NAMES[gate_id]} | {shown} | {_cell(_key(gate_id, m[gate_id]))} |")

    lines += [
        "",
        "## Provenance",
        "",
        "| Gate | Commit | Dirty tree | Env | Chip | Threads | XLA_FLAGS | Lockfile SHA-256 | Report time (UTC) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for gate_id in PHASE3_GATE_IDS:
        r = reports[gate_id]
        flags = f"`{_cell(r['xla_flags'])}`" if r["xla_flags"] else "none"
        lines.append(
            f"| {gate_id} | `{r['git_commit'][:12]}` | {_yes(r['git_dirty'])} | {r['env_name']} | {_cell(r['chip'])}"
            f" | {r['thread_count']} | {flags} | `{r['env_lock_sha256'][:12]}` | {r['timestamp_utc']} |"
        )
    lines += ["", *_consistency(reports)]

    lines += [
        "",
        "## H3 evidence",
        "",
        "H3 asks whether Phase 4 can build its ground-truth zoo on these tools, trusting that an effect they report"
        " is an effect of the edit and nothing else.",
        "",
        _verdict(status),
        "",
        "### The exactness identities (G3.1)",
        "",
        *_identities(m["G3.1"]),
        "",
        "### The J-lens experiment (G3.3)",
        "",
        *_experiment(m["G3.3"]),
        "",
        "### The fit-range meters (G3.4)",
        "",
        *_fit_range(m["G3.4"]),
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    parser.add_argument("--out", type=Path, default=SUMMARY_PATH)
    args = parser.parse_args(argv)
    paths = sorted(args.reports_dir.glob("g3*.json"))
    try:
        text = summarize(paths)
    except ValueError as exc:
        print(f"No summary written.\n{exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Summary written to {args.out}")
    return 0


