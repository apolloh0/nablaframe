"""Generate reports/phase0/summary.md from the six gate reports.

Spec: docs/specs/phase-0.md, Deliverables: "Regenerates identically from the same reports."

The summary is a pure function of the report files: no timestamps of its own, no
reading of anything else, rows sorted by gate id. It lists each gate's status and
key measurements, then states which D0 outcome the evidence supports, using the
Purpose-and-decision table in the spec. It never states a result that is not in
a report, and it refuses to run if any report fails validate_report.
"""

# summarize() raises ValueError, naming every problem, when a report is unreadable,
# invalid, or when the inputs are not exactly one report per gate. main() prints the
# problems, writes nothing and returns 1.
#
# D0, from the spec's table, over these six reports:
# * G0.1 or G0.2 fails: the PyTorch lane.
# * G0.1 to G0.4 all pass: the JAX lane. A G0.2 conditional_pass is not a fail,
#   so the summary says JAX lane on condition that its tolerance is pinned by a D-entry.
# * Otherwise G0.3 or G0.4 failed with G0.1 and G0.2 not failing. The table's
#   Revisit outcome needs a failure in both lanes, and these reports measure the
#   JAX lane only, so the summary names no outcome and says what the spec asks next.
# G0.5 and G0.6 never decide the lane; they are reported as accelerator and oracle
# policy evidence.

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from nablaframe.reports import GATE_IDS, validate_report

REPO_ROOT = Path(__file__).resolve().parent.parent

REPORTS_DIR = REPO_ROOT / "reports" / "phase0"
SUMMARY_PATH = REPORTS_DIR / "summary.md"

GATE_NAMES = {
    "G0.1": "CPU training",
    "G0.2": "Determinism",
    "G0.3": "Throughput",
    "G0.4": "Cross-check",
    "G0.5": "Metal probe",
    "G0.6": "Mode probe",
}
STATUS_TEXT = {"pass": "pass", "conditional_pass": "conditional pass", "fail": "fail"}


def summarize(report_paths: list[Path]) -> str:
    """Markdown summary. Same inputs, same output, byte for byte."""
    reports = _load(report_paths)
    m = {gate_id: report["measurements"] for gate_id, report in reports.items()}
    status = {gate_id: report["status"] for gate_id, report in reports.items()}

    lines = [
        "# Phase 0 summary",
        "",
        "Generated by `gates/summarize.py` from the six gate reports. Do not edit by hand;"
        " regenerate with `uv run python gates/summarize.py`.",
        "",
        "## D0 evidence",
        "",
        *_d0(status, m),
        "",
        "apolloh0 rules D0 at human gate H0.",
        "",
        "## Gates",
        "",
        "| Gate | Status | Key measurements |",
        "| --- | --- | --- |",
    ]
    for gate_id in GATE_IDS:
        lines.append(f"| {gate_id} {GATE_NAMES[gate_id]} | {STATUS_TEXT[status[gate_id]]} | {_key(gate_id, m[gate_id])} |")

    lines += ["", "## Accelerator and oracle policy", "", _g05_line(status["G0.5"], m["G0.5"]), "", _g06_line(m["G0.6"])]

    lines += [
        "",
        "## Environments",
        "",
        "| Gate | Env | Chip | Threads | XLA_FLAGS | Lockfile SHA-256 | Report time (UTC) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for gate_id in GATE_IDS:
        r = reports[gate_id]
        flags = f"`{_cell(r['xla_flags'])}`" if r["xla_flags"] else "none"
        lines.append(
            f"| {gate_id} | {r['env_name']} | {_cell(r['chip'])} | {r['thread_count']} | {flags}"
            f" | `{r['env_lock_sha256'][:12]}` | {r['timestamp_utc']} |"
        )
    locks = sorted({r["env_lock_sha256"] for r in reports.values()})
    lines += [
        "",
        f"All six reports come from lockfile `{locks[0]}`."
        if len(locks) == 1
        else f"The reports come from {len(locks)} different lockfiles.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    parser.add_argument("--out", type=Path, default=SUMMARY_PATH)
    args = parser.parse_args(argv)
    paths = sorted(args.reports_dir.glob("g0*.json"))
    try:
        text = summarize(paths)
    except ValueError as exc:
        print(f"No summary written.\n{exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Summary written to {args.out}")
    return 0


