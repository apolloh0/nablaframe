def _load(report_paths: list[Path]) -> dict[str, Mapping[str, Any]]:
    problems: list[str] = []
    by_gate: dict[str, list[tuple[Path, Mapping[str, Any]]]] = {}
    for path in report_paths:
        try:
            report = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            problems.append(f"{path}: cannot read JSON ({exc})")
            continue
        if not isinstance(report, Mapping):
            problems.append(f"{path}: not a JSON object")
            continue
        invalid = validate_report(report)
        if invalid:
            problems += [f"{path}: {problem}" for problem in invalid]
            continue
        by_gate.setdefault(report["gate_id"], []).append((Path(path), report))
    for gate_id in GATE_IDS:
        found = by_gate.get(gate_id, [])
        if not found:
            problems.append(f"no report for {gate_id}")
        elif len(found) > 1:
            problems.append(f"{len(found)} reports for {gate_id}: {', '.join(str(p) for p, _ in found)}")
    if problems:
        raise ValueError("cannot summarize:\n" + "\n".join(f"  - {p}" for p in problems))
    return {gate_id: by_gate[gate_id][0][1] for gate_id in GATE_IDS}


def _d0(status: dict[str, str], m: dict[str, Mapping[str, Any]]) -> list[str]:
    failed = [gate_id for gate_id in ("G0.1", "G0.2") if status[gate_id] == "fail"]
    if failed:
        return [f"The evidence supports the **PyTorch lane**: {' and '.join(failed)} failed, and the spec sends"
                " Phase 1 to the PyTorch lane when G0.1 or G0.2 fails."]
    lane_gates = ("G0.1", "G0.2", "G0.3", "G0.4")
    if all(status[gate_id] != "fail" for gate_id in lane_gates):
        if status["G0.2"] == "conditional_pass":
            diff = _num(m["G0.2"]["max_abs_param_diff"], "e")
            return [f"The evidence supports the **JAX lane**, conditionally: G0.1, G0.3 and G0.4 pass, and G0.2"
                    f" passed only within tolerance (max abs parameter diff {diff}). The spec makes that a"
                    " conditional pass with a pinned tolerance, which needs a D-entry."]
        return ["The evidence supports the **JAX lane**: G0.1 through G0.4 pass."]
    notes = ["The evidence supports **no D0 outcome yet**."]
    if status["G0.3"] == "fail":
        notes.append(f"G0.3 failed: size S trained at {_num(m['G0.3']['tokens_per_s_S'], ',')} tokens/s, below"
                     " 25,000. The spec's Revisit outcome applies when G0.3 or G0.4 fails in both lanes, and"
                     " these reports measure the JAX lane only.")
    if status["G0.4"] == "fail":
        notes.append("G0.4 failed: the spec says to diagnose the export or load path before D0.")
    return [" ".join(notes)]


def _key(gate_id: str, m: Mapping[str, Any]) -> str:
    if gate_id == "G0.1":
        return (f"{_num(m['steps'], ',')} steps; eval loss {_num(m['eval_loss_initial'], '.4f')} at step 0,"
                f" {_num(m['eval_loss_final'], '.4f')} at the end (drop {_pct(m['loss_drop_fraction'])});"
                f" NaN or Inf seen: {_yes(m['nonfinite_seen'])}")
    if gate_id == "G0.2":
        return (f"hashes identical: {_yes(m['identical'])}; single-threaded: {_yes(m['single_threaded'])};"
                f" max abs parameter diff {_num(m['max_abs_param_diff'], 'e')}")
    if gate_id == "G0.3":
        return (f"size S {_num(m['tokens_per_s_S'], ',')} tokens/s (pass at 25,000);"
                f" size M {_num(m['tokens_per_s_M'], ',')} tokens/s (recorded only)")
    if gate_id == "G0.4":
        return (f"max abs logit diff {_num(m['max_abs_logit_diff'], 'e')}; top-1 agreement"
                f" {_num(m['top1_agreement'], '.4f')} over {_num(m['positions_compared'], ',')} positions,"
                f" {_num(m['positions_near_tie'], ',')} near a tie left out")
    if gate_id == "G0.5":
        declined = m["declined_ops"]
        declined_text = "not measured" if declined is None else (", ".join(map(str, declined)) or "none")
        return (f"runs: {_yes(m['runs'])}; max relative loss diff vs CPU {_pct(m['max_rel_loss_diff'])};"
                f" {_num(m['tokens_per_s'], ',')} tokens/s; declined ops: {_cell(declined_text)}")
    return (f"bitwise equal: {_yes(m['bitwise_equal'])}; max abs logit diff {_num(m['max_abs_logit_diff'], 'e')};"
            f" seeds {', '.join(map(str, m['seeds']))}")


def _g05_line(status: str, m: Mapping[str, Any]) -> str:
    if status == "pass":
        return "G0.5 passed: the evidence supports metaljax as an accelerator. It never decides the lane."
    return "G0.5 did not pass: no accelerator, CPU only. It never decides the lane."


def _g06_line(m: Mapping[str, Any]) -> str:
    if m["bitwise_equal"] is True:
        return ("G0.6 found bitwise-identical logits on every seed, which the spec pairs with the **bitwise**"
                " oracle policy. The policy is set by a D-entry.")
    return (f"G0.6 found logits that differ (max abs diff {_num(m['max_abs_logit_diff'], 'e')}), which the spec"
            " pairs with the **instrumented canonical** policy, with τ pinned from this measurement."
            " The policy and τ are set by a D-entry.")


def _num(value: Any, style: str) -> str:
    if value is None:
        return "not measured"
    if isinstance(value, bool):
        return _yes(value)
    if style == ",":
        return f"{value:,.0f}" if isinstance(value, float) else f"{value:,}"
    if style == "e":
        return "0" if value == 0 else f"{value:.3e}"
    return format(value, style)


def _pct(value: Any) -> str:
    return "not measured" if value is None else f"{100 * value:.1f}%"


def _yes(value: Any) -> str:
    return "not measured" if value is None else ("yes" if value else "no")


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


if __name__ == "__main__":
    sys.exit(main())
