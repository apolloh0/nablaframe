def _load(report_paths: list[Path]) -> dict[str, Mapping[str, Any]]:
    problems: list[str] = []
    by_gate: dict[str, list[tuple[Path, Mapping[str, Any]]]] = {}
    for path in report_paths:
        try:
            report = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            problems.append(f"{path}: cannot read JSON ({exc})")
            continue
        if not isinstance(report, Mapping):
            problems.append(f"{path}: not a JSON object")
            continue
        invalid = validate_report(report)
        if invalid:
            problems += [f"{path}: {problem}" for problem in invalid]
            continue
        if report["gate_id"] not in PHASE2_GATE_IDS:
            problems.append(f"{path}: {report['gate_id']} is not a Phase 2 gate")
            continue
        by_gate.setdefault(report["gate_id"], []).append((Path(path), report))
    for gate_id in PHASE2_GATE_IDS:
        found = by_gate.get(gate_id, [])
        if not found:
            problems.append(f"no report for {gate_id}")
        elif len(found) > 1:
            problems.append(f"{len(found)} reports for {gate_id}: {', '.join(str(p) for p, _ in found)}")
    if problems:
        raise ValueError("cannot summarize:\n" + "\n".join(f"  - {p}" for p in problems))
    return {gate_id: by_gate[gate_id][0][1] for gate_id in PHASE2_GATE_IDS}


def _verdict(status: dict[str, str]) -> str:
    not_passed = [gate_id for gate_id in VERDICT_GATES if status[gate_id] != "pass"]
    if not not_passed:
        return ("The gates support H2: G2.1 to G2.4 and G2.6 all pass. G2.5 always passes; its numbers are"
                " below. Your own session with the scrubber is the rest of the evidence.")
    items = "\n".join(f"- {gate_id} {GATE_NAMES[gate_id]}: {STATUS_TEXT[status[gate_id]]}. The spec's next step:"
                       f" {ON_FAILURE[gate_id]}." for gate_id in not_passed)
    return f"The gates do **not** yet support H2. These gates did not pass:\n\n{items}"


def _jlens(m: Mapping[str, Any]) -> list[str]:
    errors = m["estimator_errors"]
    seconds = m.get("estimator_seconds") or {}
    lines = [
        f"- Exact reference: {_num(m['exact_positions'], ',')} positions on causal prefixes,"
        f" {_seconds(m.get('exact_seconds'))}.",
    ]
    if isinstance(errors, Mapping):
        lines += [f"- Estimator at {draws} draw{'s' if draws != '1' else ''}: relative Frobenius error"
                  f" {_num(error, '.4f')} against the exact reference, {_seconds(seconds.get(draws))}."
                  for draws, error in sorted(errors.items(), key=lambda item: _as_int(item[0]))]
    sizes = m["fit_sizes"]
    fit_seconds = m.get("fit_seconds") or {}
    if isinstance(sizes, list):
        lines += [f"- Fit at {_num(size, ',')} positions: {_seconds(fit_seconds.get(str(size)))}." for size in sizes]
    change = m["fit_change_per_doubling"]
    if isinstance(change, Mapping):
        lines += [f"- Relative change in J from {_pair(pair)} positions: {_num(value, '.4f')}."
                  for pair, value in change.items()]
    if "summed_vs_same_position" in m:
        lines.append(f"- The reference implementation's summed J, at {_num(m.get('summed_positions'), ',')} positions:"
                     f" relative Frobenius difference {_num(m['summed_vs_same_position'], '.4f')} from the"
                     f" same-position estimate, {_seconds(m.get('summed_seconds'))}. Recorded, not judged.")
    projected = m["projected_seconds"]
    lines.append(f"- Projected cost for every layer at every trace checkpoint, at the largest fit size:"
                 f" {_seconds(projected)}{_hours(projected)}.")
    lines.append(f"- Cross-check with `anthropics/jacobian-lens` feasible: {_yes(m['crosscheck_feasible'])}.")
    if m.get("reference_method"):
        lines.append(f"- How the reference computes J: {_cell(m['reference_method'])}")
    return lines


def _key(gate_id: str, m: Mapping[str, Any]) -> str:
    if gate_id == "G2.1":
        stored, expected = m["logits_bytes"], m["logits_bytes_expected"]
        off = f" ({_signed_pct((stored - expected) / expected)} from the formula)" if (
            _is_number(stored) and _is_number(expected) and expected) else ""
        return (f"{_num(m['logits_events'], ',')} logits events of {_num(m['logits_events_expected'], ',')}"
                f" expected; {_num(m['other_events_written'], ',')} other events written;"
                f" {_num(m['sample_matches'], ',')} of {_num(m['sample_size'], ',')} sampled logits events recompute"
                f" bit for bit; logits {_num(stored, ',')} bytes against {_num(expected, ',')} expected{off}")
    if gate_id == "G2.2":
        return (f"{_num(m['sample_matches'], ',')} of {_num(m['sample_size'], ',')} sampled values equal the"
                f" traced tensor bit for bit; the two passes identical: {_yes(m['builds_identical'])}")
    if gate_id == "G2.3":
        return (f"planted token recovered at {_pct(m['planted_recovery'], 2)} of positions (pass at 99%);"
                f" on random weights, best next-token accuracy {_num(m['random_max_accuracy'], 'e')} against"
                f" chance {_num(m['random_chance'], 'e')} (pass at twice chance);"
                f" largest last-layer KL {_num(m['last_layer_kl_max'], 'e')} nats (pass at 1e-5)")
    if gate_id == "G2.4":
        return (f"aligned part credited at {_pct(m['planted_aligned_credit'], 2)} of positions, perpendicular part"
                f" quiet at {_pct(m['planted_perpendicular_quiet'], 2)} (pass at 99% each); largest decomposition"
                f" error {_num(m['decomposition_error_max'], 'e')} (pass at 1e-3)")
    if gate_id == "G2.5":
        return "always passes; its numbers are under H2 evidence, for D15"
    return (f"builds identical: {_yes(m['builds_identical'])}; {_num(m['external_urls'], ',')} external URLs in"
            f" the viewer's files; export {_num(m['export_bytes'], ',')} bytes")


def _consistency(reports: Mapping[str, Mapping[str, Any]]) -> list[str]:
    lines = []
    commits = sorted({r["git_commit"] for r in reports.values()})
    locks = sorted({r["env_lock_sha256"] for r in reports.values()})
    lines.append(f"All six reports come from commit `{commits[0]}`." if len(commits) == 1
                 else f"The reports come from {len(commits)} different commits.")
    lines.append(f"All six reports come from lockfile `{locks[0]}`." if len(locks) == 1
                 else f"The reports come from {len(locks)} different lockfiles.")
    dirty = [gate_id for gate_id in PHASE2_GATE_IDS if reports[gate_id]["git_dirty"]]
    if dirty:
        lines.append(f"Written from a tree with uncommitted changes: {', '.join(dirty)}. Those reports can't be"
                     " reproduced from their commit alone.")
    return [" ".join(lines)]


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _pair(pair: str) -> str:
    """ "2048->8192" as "2,048 to 8,192"."""
    return " to ".join(f"{_as_int(size):,}" if size.isdigit() else size for size in pair.split("->"))


def _as_int(text: str) -> int:
    try:
        return int(text)
    except ValueError:
        return 0


def _num(value: Any, style: str) -> str:
    if value is None:
        return "not measured"
    if isinstance(value, bool):
        return _yes(value)
    if not _is_number(value):
        return _cell(value)
    if style == ",":
        return f"{value:,.0f}" if isinstance(value, float) else f"{value:,}"
    if style == "e":
        return "0" if value == 0 else f"{value:.3e}"
    return format(value, style)


def _seconds(value: Any) -> str:
    return "time not measured" if not _is_number(value) else f"{value:,.1f} s"


def _hours(value: Any) -> str:
    return f" (about {value / 3600:,.2f} h)" if _is_number(value) else ""


def _pct(value: Any, digits: int = 1) -> str:
    return "not measured" if value is None else f"{100 * value:.{digits}f}%"


def _signed_pct(value: float) -> str:
    return f"{100 * value:+.2f}%"


def _yes(value: Any) -> str:
    return "not measured" if value is None else ("yes" if value else "no")


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


if __name__ == "__main__":
    raise SystemExit(main())
