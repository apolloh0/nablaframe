"""The Phase 2 summary: reports/phase2/summary.md, from the six Phase 2 reports.

Same shape and rules as gates/phase1/summarize.py: refuses a missing report or one whose
status contradicts its measurements, lists each gate that did not pass with the spec's
next step, and gives byte-identical output on two runs. It ends with the evidence for
human gate H2, including G2.5's numbers for D15's ruling.
"""

# summarize() raises ValueError, naming every problem, when a report is unreadable,
# invalid (validate_report, which includes the status rules), not a Phase 2 report, or
# when the inputs are not exactly one report per gate. main() prints the problems,
# writes nothing and returns 1.
#
# A pure function of the report files: no timestamps of its own, rows in gate order.
# The verdict reads statuses only. G2.5 always passes, so the verdict covers G2.1 to
# G2.4 and G2.6, and G2.5's numbers are listed for D15 without a verdict of their own.
# Reports written from a dirty tree, or from different commits or lockfiles, are named
# as such. It never states a result that is not in a report. apolloh0 rules H2.
#
# Run in nf-jax: ``UV_PROJECT_ENVIRONMENT=.venv-jax uv run --extra jax python
# gates/phase2/summarize.py``.

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from nablaframe.reports import PHASE2_GATE_IDS, validate_report

REPO_ROOT = Path(__file__).resolve().parents[2]
REPORTS_DIR = REPO_ROOT / "reports" / "phase2"
SUMMARY_PATH = REPORTS_DIR / "summary.md"

GATE_NAMES = {
    "G2.1": "Logits in the trace",
    "G2.2": "Readout fidelity",
    "G2.3": "Logit lens",
    "G2.4": "Direct logit attribution",
    "G2.5": "J-lens cost probe",
    "G2.6": "Viewer",
}
# The spec's "On failure" column, docs/specs/phase-2.md, Gates.
ON_FAILURE = {
    "G2.1": "diagnose the engine",
    "G2.2": "diagnose the decoder",
    "G2.3": "diagnose before shipping the view",
    "G2.4": "diagnose before shipping the view",
    "G2.5": "not applicable; the results set D15's method and size",
    "G2.6": "diagnose the export",
}
VERDICT_GATES = tuple(gate_id for gate_id in PHASE2_GATE_IDS if gate_id != "G2.5")
STATUS_TEXT = {"pass": "pass", "conditional_pass": "conditional pass", "fail": "fail"}


def summarize(report_paths: list[Path]) -> str:
    reports = _load(report_paths)
    m = {gate_id: report["measurements"] for gate_id, report in reports.items()}
    status = {gate_id: report["status"] for gate_id, report in reports.items()}

    lines = [
        "# Phase 2 summary",
        "",
        "Generated by `gates/phase2/summarize.py` from the six Phase 2 gate reports. Do not edit by hand;"
        " regenerate with `UV_PROJECT_ENVIRONMENT=.venv-jax uv run --extra jax python gates/phase2/summarize.py`.",
        "",
        "## Gates",
        "",
        "| Gate | Status | Key measurements |",
        "| --- | --- | --- |",
    ]
    for gate_id in PHASE2_GATE_IDS:
        shown = "always passes" if gate_id == "G2.5" else STATUS_TEXT[status[gate_id]]
        lines.append(f"| {gate_id} {GATE_NAMES[gate_id]} | {shown} | {_cell(_key(gate_id, m[gate_id]))} |")

    lines += [
        "",
        "## Provenance",
        "",
        "| Gate | Commit | Dirty tree | Env | Chip | Threads | XLA_FLAGS | Lockfile SHA-256 | Report time (UTC) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for gate_id in PHASE2_GATE_IDS:
        r = reports[gate_id]
        flags = f"`{_cell(r['xla_flags'])}`" if r["xla_flags"] else "none"
        lines.append(
            f"| {gate_id} | `{r['git_commit'][:12]}` | {_yes(r['git_dirty'])} | {r['env_name']} | {_cell(r['chip'])}"
            f" | {r['thread_count']} | {flags} | `{r['env_lock_sha256'][:12]}` | {r['timestamp_utc']} |"
        )
    lines += ["", *_consistency(reports)]

    lines += [
        "",
        "## H2 evidence",
        "",
        "H2 asks whether these views are faithful enough for Phase 3 to manipulate the model through them.",
        "",
        _verdict(status),
        "",
        "### For D15: the J-lens cost probe (G2.5)",
        "",
        *_jlens(m["G2.5"]),
        "",
        "apolloh0 rules H2, and D15's method and fit-sample size.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    parser.add_argument("--out", type=Path, default=SUMMARY_PATH)
    args = parser.parse_args(argv)
    paths = sorted(args.reports_dir.glob("g2*.json"))
    try:
        text = summarize(paths)
    except ValueError as exc:
        print(f"No summary written.\n{exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Summary written to {args.out}")
    return 0


