"""Generate reports/phase1/summary.md from the six Phase 1 gate reports: the H1 evidence.

Spec: docs/specs/phase-1.md, "Gates". A pure function of the report files, byte
for byte: no timestamps of its own, rows sorted by gate id. It refuses to run if
any report is missing or fails ``validate_report``. It lists each gate's status
and key measurements, the vocabulary D8 selected, and a verdict: Phase 2 can build
on the engine only if all six pass; otherwise it names what failed. It never
states a result that is not in a report. apolloh0 rules H1.
"""

# summarize() raises ValueError, naming every problem, when a report is unreadable,
# invalid, not a Phase 1 report, or when the inputs are not exactly one report per
# gate. main() prints the problems, writes nothing and returns 1.
#
# The verdict reads statuses only: "pass" on all six, or a list of every gate that
# did not pass, each with what the spec's "On failure" column says comes next. A
# G1.3 conditional_pass is not a pass. Reports written from a dirty tree, or from
# different commits or lockfiles, are named as such, since each report must be
# reproducible from its commit.

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from nablaframe.reports import PHASE1_GATE_IDS, validate_report

REPO_ROOT = Path(__file__).resolve().parents[2]
REPORTS_DIR = REPO_ROOT / "reports" / "phase1"
SUMMARY_PATH = REPORTS_DIR / "summary.md"

GATE_NAMES = {
    "G1.1": "Tokenizer and corpus",
    "G1.2": "Parity",
    "G1.3": "Trainer determinism",
    "G1.4": "Reference run",
    "G1.5": "Oracle on the real model",
    "G1.6": "Trace and recompute",
}
# The spec's "On failure" column, docs/specs/phase-1.md, Gates.
ON_FAILURE = {
    "G1.1": "fix the pipeline",
    "G1.2": "diagnose before training anything",
    "G1.3": "rule in a D-entry before G1.4",
    "G1.4": "diagnose; nothing downstream runs",
    "G1.5": "a D-entry on the policy, per D6",
    "G1.6": "diagnose the engine",
}
STATUS_TEXT = {"pass": "pass", "conditional_pass": "conditional pass", "fail": "fail"}


def summarize(report_paths: list[Path]) -> str:
    reports = _load(report_paths)
    m = {gate_id: report["measurements"] for gate_id, report in reports.items()}
    status = {gate_id: report["status"] for gate_id, report in reports.items()}

    lines = [
        "# Phase 1 summary",
        "",
        "Generated by `gates/phase1/summarize.py` from the six Phase 1 gate reports. Do not edit by hand;"
        " regenerate with `UV_PROJECT_ENVIRONMENT=.venv-jax uv run --extra jax python gates/phase1/summarize.py`.",
        "",
        "## H1 evidence",
        "",
        _verdict(status),
        "",
        _vocabulary(status["G1.1"], m["G1.1"]),
        "",
        "apolloh0 rules H1.",
        "",
        "## Gates",
        "",
        "| Gate | Status | Key measurements |",
        "| --- | --- | --- |",
    ]
    for gate_id in PHASE1_GATE_IDS:
        lines.append(f"| {gate_id} {GATE_NAMES[gate_id]} | {STATUS_TEXT[status[gate_id]]}"
                     f" | {_cell(_key(gate_id, m[gate_id]))} |")

    lines += [
        "",
        "## Provenance",
        "",
        "| Gate | Commit | Dirty tree | Env | Chip | Threads | XLA_FLAGS | Lockfile SHA-256 | Report time (UTC) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for gate_id in PHASE1_GATE_IDS:
        r = reports[gate_id]
        flags = f"`{_cell(r['xla_flags'])}`" if r["xla_flags"] else "none"
        lines.append(
            f"| {gate_id} | `{r['git_commit'][:12]}` | {_yes(r['git_dirty'])} | {r['env_name']} | {_cell(r['chip'])}"
            f" | {r['thread_count']} | {flags} | `{r['env_lock_sha256'][:12]}` | {r['timestamp_utc']} |"
        )
    lines += ["", *_consistency(reports)]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    parser.add_argument("--out", type=Path, default=SUMMARY_PATH)
    args = parser.parse_args(argv)
    paths = sorted(args.reports_dir.glob("g1*.json"))
    try:
        text = summarize(paths)
    except ValueError as exc:
        print(f"No summary written.\n{exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Summary written to {args.out}")
    return 0


