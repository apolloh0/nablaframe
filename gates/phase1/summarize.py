def _load(report_paths: list[Path]) -> dict[str, Mapping[str, Any]]:
    problems: list[str] = []
    by_gate: dict[str, list[tuple[Path, Mapping[str, Any]]]] = {}
    for path in report_paths:
        try:
            report = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            problems.append(f"{path}: cannot read JSON ({exc})")
            continue
        if not isinstance(report, Mapping):
            problems.append(f"{path}: not a JSON object")
            continue
        invalid = validate_report(report)
        if invalid:
            problems += [f"{path}: {problem}" for problem in invalid]
            continue
        if report["gate_id"] not in PHASE1_GATE_IDS:
            problems.append(f"{path}: {report['gate_id']} is not a Phase 1 gate")
            continue
        by_gate.setdefault(report["gate_id"], []).append((Path(path), report))
    for gate_id in PHASE1_GATE_IDS:
        found = by_gate.get(gate_id, [])
        if not found:
            problems.append(f"no report for {gate_id}")
        elif len(found) > 1:
            problems.append(f"{len(found)} reports for {gate_id}: {', '.join(str(p) for p, _ in found)}")
    if problems:
        raise ValueError("cannot summarize:\n" + "\n".join(f"  - {p}" for p in problems))
    return {gate_id: by_gate[gate_id][0][1] for gate_id in PHASE1_GATE_IDS}


def _verdict(status: dict[str, str]) -> str:
    not_passed = [gate_id for gate_id in PHASE1_GATE_IDS if status[gate_id] != "pass"]
    if not not_passed:
        return "The evidence supports building Phase 2 on this engine: G1.1 through G1.6 all pass."
    items = "\n".join(f"- {gate_id} {GATE_NAMES[gate_id]}: {STATUS_TEXT[status[gate_id]]}. The spec's next step:"
                       f" {ON_FAILURE[gate_id]}." for gate_id in not_passed)
    return ("The evidence does **not** yet support building Phase 2 on this engine. These gates did not pass:"
            f"\n\n{items}")


def _vocabulary(status: str, m: Mapping[str, Any]) -> str:
    selected, rate = m["vocab_selected"], m["unk_rate_4096"]
    if selected is None:
        return "G1.1 selected no vocabulary."
    text = (f"D8 selects a vocabulary of **{_num(selected, ',')}**: G1.1 measured an unknown-word rate of"
            f" {_pct(rate, 2)} at 4,096, against D8's limit of 1.0%.")
    if status != "pass":
        text += " G1.1 did not pass, so that selection stands on a failed gate."
    return text


def _key(gate_id: str, m: Mapping[str, Any]) -> str:
    if gate_id == "G1.1":
        return (f"vocabulary {_num(m['vocab_selected'], ',')}; unknown-word rate {_pct(m['unk_rate_4096'], 2)} at"
                f" 4,096, {_pct(m['unk_rate_8192'], 2)} at 8,192, {_pct(m['unk_rate_4096_cased'], 2)} at 4,096"
                f" without lowercasing; builds identical: {_yes(m['builds_identical'])};"
                f" {_num(m['train_tokens'], ',')} train and {_num(m['validation_tokens'], ',')} validation tokens;"
                f" {_num(m['stories_dropped'], ',')} stories dropped")
    if gate_id == "G1.2":
        return (f"{_num(m['n_params'], ',')} parameters, {_num(m['n_params_expected'], ',')} expected;"
                f" max abs logit diff {_num(m['max_abs_logit_diff'], 'e')} (pass at 1e-4);"
                f" top-1 agreement {_num(m['top1_agreement'], '.4f')},"
                f" {_num(m['positions_near_tie'], ',')} positions near a tie left out")
    if gate_id == "G1.3":
        return (f"hashes identical: {_yes(m['identical'])}; single-threaded: {_yes(m['single_threaded'])};"
                f" max abs parameter diff {_num(m['max_abs_param_diff'], 'e')}")
    if gate_id == "G1.4":
        return (f"{_num(m['steps'], ',')} steps, {_num(m['tokens'], ',')} tokens; final validation loss"
                f" {_num(m['final_val_loss'], '.4f')} against {_num(m['bigram_val_loss'], '.4f')} for the"
                f" add-one bigram model; {_num(m['checkpoints_written'], ',')} of"
                f" {_num(m['checkpoints_scheduled'], ',')} trace checkpoints written;"
                f" NaN or Inf seen: {_yes(m['nonfinite_seen'])}")
    if gate_id == "G1.5":
        steps = m["steps_checked"]
        steps_text = ", ".join(_num(step, ",") for step in steps) if isinstance(steps, list) else "not measured"
        return (f"bitwise equal at steps {steps_text}: {_yes(m['bitwise_equal'])};"
                f" 1e-3 added at blocks.0.hook_resid_post detected: {_yes(m['defect_detected'])}")
    stored, expected = m["store_bytes"], m["store_bytes_expected"]
    off = f" ({_signed_pct((stored - expected) / expected)} from the formula)" if (
        _is_number(stored) and _is_number(expected) and expected) else ""
    return (f"{_num(m['events_recorded'], ',')} events recorded; {_num(m['sample_matches'], ',')} of"
            f" {_num(m['sample_size'], ',')} sampled events recompute to their hash; the second trace wrote"
            f" {_num(m['retrace_new_events'], ',')} events; store {_num(stored, ',')} bytes against"
            f" {_num(expected, ',')} expected{off}")


def _consistency(reports: Mapping[str, Mapping[str, Any]]) -> list[str]:
    lines = []
    commits = sorted({r["git_commit"] for r in reports.values()})
    locks = sorted({r["env_lock_sha256"] for r in reports.values()})
    lines.append(f"All six reports come from commit `{commits[0]}`." if len(commits) == 1
                 else f"The reports come from {len(commits)} different commits.")
    lines.append(f"All six reports come from lockfile `{locks[0]}`." if len(locks) == 1
                 else f"The reports come from {len(locks)} different lockfiles.")
    dirty = [gate_id for gate_id in PHASE1_GATE_IDS if reports[gate_id]["git_dirty"]]
    if dirty:
        lines.append(f"Written from a tree with uncommitted changes: {', '.join(dirty)}. Those reports can't be"
                     " reproduced from their commit alone.")
    return [" ".join(lines)]


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _num(value: Any, style: str) -> str:
    if value is None:
        return "not measured"
    if isinstance(value, bool):
        return _yes(value)
    if style == ",":
        return f"{value:,.0f}" if isinstance(value, float) else f"{value:,}"
    if style == "e":
        return "0" if value == 0 else f"{value:.3e}"
    return format(value, style)


def _pct(value: Any, digits: int = 1) -> str:
    return "not measured" if value is None else f"{100 * value:.{digits}f}%"


def _signed_pct(value: float) -> str:
    return f"{100 * value:+.2f}%"


def _yes(value: Any) -> str:
    return "not measured" if value is None else ("yes" if value else "no")


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


if __name__ == "__main__":
    sys.exit(main())
